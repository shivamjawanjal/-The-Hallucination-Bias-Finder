@app.post("/api/analyze")
def analyze_text(req: AnalyzeRequest):
    if not req.text or not req.text.strip():
        raise HTTPException(status_code=400, detail="Text cannot be empty.")
    
    api_key = req.api_key or os.getenv("GEMINI_API_KEY")
    
    if api_key and len(api_key.strip()) > 10:
        result = call_gemini_analysis(
            text=req.text,
            api_key=api_key.strip(),
            model_name=req.model_name or "gemini-2.5-flash",
            rigor=req.rigor or "deep"
        )
    else:
        # Run local intelligent mock analysis
        result = run_mock_analysis(req.text)
        result["simulated"] = True
    
    return result

@app.post("/api/chat")
def chat_with_detective(req: ChatRequest):
    api_key = req.api_key or os.getenv("GEMINI_API_KEY")
    
    # Construct context prompt
    context_str = ""
    if req.context_text:
        context_str += f"\n<original_analyzed_text>\n{req.context_text}\n</original_analyzed_text>"
    if req.context_analysis:
        context_str += f"\n<audit_report_json>\n{json.dumps(req.context_analysis, indent=2)}\n</audit_report_json>"
    
    last_user_msg = req.messages[-1].content if req.messages else "Hello"
    
    if api_key and len(api_key.strip()) > 10:
        try:
            from google import genai
            client = genai.Client(api_key=api_key.strip())
            
            conversation_history = []
            for msg in req.messages[:-1]:
                conversation_history.append(f"{msg.role.upper()}: {msg.content}")
            
            prompt = f"{PROMPT_CHAT_ASSISTANT}\n{context_str}\n\nRecent History:\n" + "\n".join(conversation_history) + f"\n\nUSER: {last_user_msg}\nASSISTANT:"
            
            response = client.models.generate_content(
                model=req.model_name or "gemini-2.5-flash",
                contents=prompt
            )
            return {"reply": response.text.strip()}
        except Exception as e:
            return {"reply": f"Detective response (Simulation): Based on the Chain-of-Verification audit, the claims were cross-referenced against empirical benchmarks. Regarding your query: '{last_user_msg}', our verification notes highlight discrepancies in the baseline truth grounding. (Error note: {str(e)[:80]})"}
    else:
        # Interactive mock response
        return {
            "reply": f"Detective response: I reviewed the audit report. Regarding your question '{last_user_msg}', our Chain-of-Verification protocol isolates every atomic claim and formulates independent verification queries. If you need any specific claim re-checked or re-worded for your college presentation, let me know!"
        }

