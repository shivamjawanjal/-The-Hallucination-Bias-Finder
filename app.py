# ----------------- Core Gemini API Call ----------------- #
def call_gemini_analysis(text: str, api_key: str, model_name: str = "gemini-2.5-flash", rigor: str = "deep") -> Dict[str, Any]:
    """Invokes Google Gemini SDK using strict Chain-of-Verification and prompt engineering constraints."""
    try:
        from google import genai
        from google.genai import types

        client = genai.Client(api_key=api_key)
        
        # Rigor modulation in prompt
        rigor_instruction = ""
        if rigor == "fast":
            rigor_instruction = "Perform an efficient, high-level verification targeting the top 3-4 most critical claims."
        elif rigor == "deep":
            rigor_instruction = "Perform exhaustive atomic deconstruction. Check every single clause, statistic, date, and attribution."
        else:
            rigor_instruction = "Perform a balanced assessment of major factual claims and framing rhetoric."

        user_content = f"""<rigor_instruction>
{rigor_instruction}
</rigor_instruction>

<user_submission>
{text}
</user_submission>

Execute the Chain-of-Verification (CoVe) and Cognitive Bias protocol on the text inside `<user_submission>`. Return ONLY valid JSON adhering strictly to the schema provided."""

        # Call model
        chosen_model = model_name or "gemini-2.5-flash"
        response = client.models.generate_content(
            model=chosen_model,
            contents=user_content,
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_PROMPT_COVE,
                temperature=0.15, # Low temperature ensures strict adherence and minimizes creative hallucinations
                response_mime_type="application/json"
            )
        )
        
        raw_text = response.text.strip()
        # Parse JSON
        if raw_text.startswith("```"):
            raw_text = re.sub(r"^```(?:json)?\n?", "", raw_text)
            raw_text = re.sub(r"\n?```$", "", raw_text)
        
        return json.loads(raw_text)

    except Exception as e:
        print(f"Gemini API invocation note/error: {e}")
        # Fallback to intelligent mock if API error occurred (quota, invalid key, or model name mismatch)
        result = run_mock_analysis(text)
        result["summary"] += f" (Note: Live API encountered: {str(e)[:120]}... Fallback simulation applied)."
        return result

